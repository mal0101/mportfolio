// Bakes assets/photos/malak-portrait.jpg into lib/portrait-tones.ts: a 120x150 luminance grid plus a hand-drawn
// silhouette matte (the background is two-tone, so luminance alone cannot separate her from it). A median, local
// contrast (CLAHE), an unsharp mask and a gamma lift run first so eyes, brows, nostrils and lips survive the halftone.
// One byte per sample: high nibble luminance, low nibble matte.
// Run manually: pnpm portrait:tones. The output is committed and byte-identical across runs.
// Set DEBUG_DIR to also write a matte overlay PNG (halftone previews are rendered from lib/portrait.ts by hand).
import sharp from "sharp"
import { writeFileSync, mkdirSync } from "node:fs"
import { fileURLToPath } from "node:url"
import path from "node:path"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const SRC = path.join(root, "assets/photos/malak-portrait.jpg")
const OUT = path.join(root, "lib/portrait-tones.ts")
const GW = 120
const GH = 150
const W = 500
const H = 625
// Tuned by eye against 360px (6px dots) and 240px (4px dots) previews (DESIGN §5.11). The median kills skin texture
// that would otherwise read as dot noise; CLAHE on 64px tiles and a 2.5-sample unsharp mask work at feature scale
// (eyes, brows, nostrils, lips are 1-3 dots tall), not pixel scale; gamma < 1 opens the skin so features read as gaps.
const MEDIAN = 3
const CLAHE = { width: 64, height: 64, maxSlope: 4 }
const SHARPEN = { sigma: 2.5, m1: 1.5, m2: 3 }
const GAMMA = 0.85
const STRETCH = [0.02, 0.995] // percentile stretch inside the matte

// Silhouette in source pixels: head, hair mass and shoulders down to the bottom edge, clockwise from the crown.
const POLY = [
  [240, 28],
  [290, 48],
  [325, 100],
  [340, 170],
  [348, 240],
  [368, 305],
  [398, 350],
  [420, 415],
  [438, 485],
  [454, 550],
  [464, 600],
  [466, 625],
  [0, 625],
  [0, 345],
  [8, 270],
  [22, 200],
  [52, 130],
  [95, 70],
  [160, 36],
]
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}"><rect width="${W}" height="${H}" fill="black"/><polygon fill="white" points="${POLY.map((p) => p.join(",")).join(" ")}"/></svg>`

const raw = (img) => img.greyscale().raw().toBuffer()
const enhanced = await sharp(SRC).resize(W, H, { fit: "fill" }).greyscale().median(MEDIAN).clahe(CLAHE).png().toBuffer()
const lum = await raw(sharp(enhanced).resize(GW, GH, { kernel: "lanczos3", fit: "fill" }).sharpen(SHARPEN))
const matte = await raw(sharp(Buffer.from(svg)).blur(6).resize(GW, GH))

const inside = []
for (let i = 0; i < lum.length; i++) if (matte[i] / 255 > 0.5) inside.push(lum[i] / 255)
inside.sort((a, b) => a - b)
const pct = (p) => inside[Math.min(inside.length - 1, Math.floor(p * inside.length))]
const lo = pct(STRETCH[0])
const hi = pct(STRETCH[1])

const out = Buffer.alloc(GW * GH)
for (let i = 0; i < out.length; i++) {
  const l = Math.min(1, Math.max(0, (lum[i] / 255 - lo) / (hi - lo))) ** GAMMA
  out[i] = (Math.round(l * 15) << 4) | Math.round((matte[i] / 255) * 15)
}
writeFileSync(
  OUT,
  `// Generated by scripts/portrait-tones.mjs from assets/photos/malak-portrait.jpg — do not edit.\nexport const TONES = { gw: ${GW}, gh: ${GH}, srcW: ${W}, srcH: ${H}, data: "${out.toString("base64")}" } as const\n`,
)
console.log(`wrote ${path.relative(root, OUT)} (percentiles ${lo.toFixed(3)}..${hi.toFixed(3)})`)

const dbg = process.env.DEBUG_DIR
if (dbg) {
  mkdirSync(dbg, { recursive: true })
  const mask = await sharp(Buffer.from(svg)).blur(6).greyscale().raw().toBuffer()
  const red = Buffer.alloc(W * H * 4)
  for (let i = 0; i < W * H; i++) {
    red[i * 4] = 255
    red[i * 4 + 3] = Math.round(((255 - mask[i]) / 255) * 140) // tint what is EXCLUDED
  }
  await sharp(SRC)
    .composite([{ input: red, raw: { width: W, height: H, channels: 4 } }])
    .png()
    .toFile(path.join(dbg, "matte-overlay.png"))
  await sharp(enhanced).png().toFile(path.join(dbg, "enhanced.png"))
}
